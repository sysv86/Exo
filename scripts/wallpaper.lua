local ignis = require("ignis")
local utils = ignis.utils

local user_settings = require("user_settings")
local paths = require("paths")
local send_notification = require("scripts.send_notification")

local css_manager = ignis.CssManager.get_default()
local command_manager = ignis.CommandManager.get_default()

local SCHEMES = {
    "content", "expressive", "fidelity", "fruit-salad",
    "monochrome", "neutral", "rainbow", "tonal-spot", "vibrant",
}

local Wallpaper = {
    _preview_gen_id = 0,
}

local function normalize_scheme(name)
    if not name or name == "" then return "expressive" end
    local norm = tostring(name):gsub("_", "-"):gsub("^scheme%-", "")
    for _, scheme in ipairs(SCHEMES) do
        if scheme == norm then return scheme end
    end
    return "expressive"
end

local function current_mode()
    return user_settings.appearance.wallcolors.dark_mode and "dark" or "light"
end

local function have_program(name)
    local ok, lgi = pcall(require, "lgi")
    if ok and lgi.GLib and lgi.GLib.find_program_in_path then
        return lgi.GLib.find_program_in_path(name) ~= nil
    end
    return false
end

local function shell_quote(value)
    return "'" .. (tostring(value):gsub("'", "'\\''")) .. "'"
end

local function parse_matugen_colors(stdout, target_mode)
    if not stdout or stdout == "" then return nil end
    local ok, data = pcall(utils.json_decode, stdout)
    if not ok or type(data) ~= "table" or type(data.colors) ~= "table" then
        return nil
    end
    local colors = data.colors
    local extracted = {}
    if type(colors[target_mode]) == "table" then
        for name, value in pairs(colors[target_mode]) do
            if type(value) == "table" and value.color then
                extracted[name] = tostring(value.color)
            else
                extracted[name] = tostring(value)
            end
        end
    else
        for name, values in pairs(colors) do
            if type(values) == "table" and values[target_mode] then
                local v = values[target_mode]
                if type(v) == "table" and v.color then
                    extracted[name] = tostring(v.color)
                else
                    extracted[name] = tostring(v)
                end
            end
        end
    end
    if next(extracted) == nil then return nil end
    return extracted
end

local function to_camel_case(snake)
    return (snake:gsub("_(%a)", function(c) return c:upper() end))
end

local function write_colors_scss(colors_map, wallpaper_path)
    if not colors_map then return false end
    local lines = {
        "/* Generated by IgnisLua Wallpaper script (Material 3 Expressive) */",
        string.format('$image: "%s";', tostring(wallpaper_path or "")),
    }
    local keys = {}
    for k in pairs(colors_map) do
        keys[#keys + 1] = k
    end
    table.sort(keys)
    for _, k in ipairs(keys) do
        local snake_name = k:gsub("-", "_")
        local camel_name = to_camel_case(snake_name)
        lines[#lines + 1] = string.format("$%s: %s;", snake_name, colors_map[k])
        if camel_name ~= snake_name then
            lines[#lines + 1] = string.format("$%s: %s;", camel_name, colors_map[k])
        end
    end
    lines[#lines + 1] = ""
    local wrote = pcall(utils.write_file, paths.COLORS_FILE, table.concat(lines, "\n"))
    if wrote then
        pcall(function() require("modules.m3components.palette").clear_cache() end)
    end
    return wrote
end


local function load_shipped_palettes()
    local ok, text = pcall(utils.read_file, paths.PALETTES_FILE)
    if not ok or not text or text == "" then return nil end
    local vars = {}
    for name, value in text:gmatch("%$([%w_%-]+)%s*:%s*([^;]+);") do
        vars[name] = value
    end
    if next(vars) == nil then return nil end
    return vars
end

---@param scheme string
---@param mode string "light" or "dark"
---@param wallpaper_path string|nil
---@return boolean applied
local function apply_shipped_colors(scheme, mode, wallpaper_path)
    local vars = load_shipped_palettes()
    if not vars then return false end
    local prefix = normalize_scheme(scheme) .. "-" .. tostring(mode)
    local escape = prefix:gsub("%-", "%%-")
    local map = {}
    for name, value in pairs(vars) do
        local color = name:match("^" .. escape .. "%-(.+)$")
        if color then
            map[color] = value
        end
    end
    if next(map) == nil then return false end
    return write_colors_scss(map, wallpaper_path)
end

local function run_matugen(path, scheme, mode, on_done)
    if not have_program("matugen") then
        local applied = apply_shipped_colors(scheme, mode, path)
        if applied then
            css_manager:reload_all_css()
        end
        if on_done then on_done(applied) end
        return
    end
    if not path or path == "" or not utils.file_exists(path) then
        local applied = apply_shipped_colors(scheme, mode, path)
        if applied then
            css_manager:reload_all_css()
        end
        if on_done then on_done(applied) end
        return
    end
    local resolved_scheme = normalize_scheme(scheme)
    local cmd = string.format(
        "matugen image -t scheme-%s %s -m %s --prefer=saturation >/dev/null 2>&1; " ..
        "matugen image -t scheme-%s %s -m %s --prefer=saturation --json hex --dry-run 2>/dev/null",
        resolved_scheme, shell_quote(path), shell_quote(mode),
        resolved_scheme, shell_quote(path), shell_quote(mode)
    )
    utils.exec_sh_async(cmd, function(res)
        local wrote = false
        if res and res.stdout and res.stdout ~= "" then
            local cmap = parse_matugen_colors(res.stdout, mode)
            if cmap then
                wrote = write_colors_scss(cmap, path)
            end
        end
        if not wrote then
            apply_shipped_colors(resolved_scheme, mode, path)
        end
        css_manager:reload_all_css()
        if on_done then on_done(true) end
    end)
end

--- Applies a wallpaper and regenerates the colour scheme from it.
---@param path string
function Wallpaper.set_wall(path)
    if not path or path == "" then return end

    user_settings.appearance.wallcolors.wallpaper_path = path
    send_notification("Wallpaper Set!", path:match("([^/]+)$") or path)

    run_matugen(path, user_settings.appearance.wallcolors.color_scheme, current_mode(), function()
        Wallpaper.generate_previews(true)
    end)
end

--- Regenerates colours for a different Matugen scheme.
---@param color_scheme string
function Wallpaper.set_colors(color_scheme)
    local path = user_settings.appearance.wallcolors.wallpaper_path
    local resolved_scheme = normalize_scheme(color_scheme)
    user_settings.appearance.wallcolors.color_scheme = resolved_scheme

    run_matugen(path, resolved_scheme, current_mode(), function()
        Wallpaper.generate_previews(false)
    end)
end

--- Switches between the light and dark theme.
---@param active boolean true = dark
function Wallpaper.set_dark_mode(active)
    local color_scheme = user_settings.appearance.wallcolors.color_scheme
    local path = user_settings.appearance.wallcolors.wallpaper_path
    local mode = active and "dark" or "light"

    user_settings.appearance.wallcolors.dark_mode = active

    if active then
        if css_manager:get_css_info_by_name("lightthemeoverrides") then
            css_manager:remove_css("lightthemeoverrides")
        end
    else
        if not css_manager:get_css_info_by_name("lightthemeoverrides") then
            local info = ignis.CssInfoPath({
                name = "lightthemeoverrides",
                path = paths.STYLES_DIR .. "/lightthemeoverrides.scss",
                compiler_function = function(p)
                    return utils.sass_compile({ path = p })
                end,
                priority = "user",
            })
            css_manager:apply_css(info)
        end
    end

    utils.exec_sh_async(string.format(
        "gsettings set org.gnome.desktop.interface color-scheme 'prefer-%s' 2>/dev/null", mode))

    if path and path ~= "" then
        run_matugen(path, color_scheme, mode, function()
            Wallpaper.generate_previews(false)
        end)
    else
        Wallpaper.sync_colors()
        css_manager:reload_all_css()
    end
end

--- Applies the stored palette and light/dark theme from shipped palettes.
---@return boolean applied
function Wallpaper.sync_colors()
    local wallcolors = user_settings.appearance.wallcolors
    if have_program("matugen") and wallcolors.wallpaper_path ~= "" then
        run_matugen(wallcolors.wallpaper_path, wallcolors.color_scheme, current_mode(), nil)
        return true
    end
    local applied = apply_shipped_colors(wallcolors.color_scheme, current_mode(), wallcolors.wallpaper_path)
    if applied then
        pcall(function() css_manager:reload_all_css() end)
    end
    return applied
end

--- Extracts colour swatches for every scheme/mode asynchronously.
---@param force? boolean
function Wallpaper.generate_previews(force)
    if not have_program("matugen") then
        return
    end

    if not force and utils.file_exists(paths.PREVIEW_COLORS_FILE) then
        local ok, existing = pcall(utils.read_file, paths.PREVIEW_COLORS_FILE)
        if ok and existing and #existing > 64 then
            return
        end
    end

    local path = user_settings.appearance.wallcolors.wallpaper_path
    if not path or path == "" or not utils.file_exists(path) then
        return
    end

    local mode = current_mode()
    local scheme = normalize_scheme(user_settings.appearance.wallcolors.color_scheme)

    Wallpaper._preview_gen_id = Wallpaper._preview_gen_id + 1
    local gen_id = Wallpaper._preview_gen_id

    local tasks = {}
    for _, target_scheme in ipairs(SCHEMES) do
        tasks[#tasks + 1] = {
            prefix = "palette-" .. target_scheme,
            scheme = target_scheme,
            mode = mode,
        }
    end
    for _, target_mode in ipairs({ "light", "dark" }) do
        tasks[#tasks + 1] = {
            prefix = "theme-" .. target_mode,
            scheme = scheme,
            mode = target_mode,
        }
    end

    local scss = {}
    local idx = 1

    local function step()
        if gen_id ~= Wallpaper._preview_gen_id then
            return
        end
        if idx > #tasks then
            if #scss > 0 then
                table.sort(scss)
                pcall(utils.write_file, paths.PREVIEW_COLORS_FILE, table.concat(scss))
                css_manager:reload_all_css()
            end
            return
        end

        local t = tasks[idx]
        idx = idx + 1
        local cmd = string.format(
            "matugen image -t scheme-%s %s -m %s --prefer=saturation --json hex --dry-run 2>/dev/null",
            t.scheme, shell_quote(path), t.mode
        )
        utils.exec_sh_async(cmd, function(res)
            if gen_id ~= Wallpaper._preview_gen_id then
                return
            end
            if res and res.stdout and res.stdout ~= "" then
                local cmap = parse_matugen_colors(res.stdout, t.mode)
                if cmap then
                    for name, val in pairs(cmap) do
                        local var = string.format("%s-%s", t.prefix, (name:gsub("_", "-")))
                        scss[#scss + 1] = string.format("$%s: %s;\n", var, val)
                    end
                end
            end
            step()
        end)
    end

    step()
end

command_manager:add_command("set-wallpaper", function(path)
    Wallpaper.set_wall(path)
end)

return Wallpaper
